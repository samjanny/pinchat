#!/usr/bin/env node

/**
 * Ratchet Correctness Test Suite
 *
 * Regression coverage for three findings bundled in
 * `fix(crypto): ratchet correctness + non-extractable DH keys`:
 *
 *   C-01  encryptMessage / decryptMessage are now serialized through an
 *         internal promise mutex. Two concurrent encrypts must NOT read a
 *         stale chainKeyMaterial between deriveMessageKey() and ratchet().
 *
 *   C-02  Late messages whose key is sitting in this.skippedKeys must
 *         decrypt without triggering a spurious DH ratchet on an OLD dh.
 *         The receive path now checks skippedKeys before the isNewKey
 *         branch and returns the plaintext flagged as _outOfOrder=true.
 *
 *   C-05  Every DH keypair generated by the Double Ratchet (initialize,
 *         performDHRatchetOnReceive, performSendSideDHRatchet) and every
 *         imported peer DH public key (this.DHr) must be non-extractable.
 *
 * Unlike the legacy test-double-ratchet.js, this file imports the REAL
 * production modules under static/js/. Drift between tested and shipped
 * code is the bug we are NOT going to repeat.
 */

'use strict';

const assert = require('assert');
const { webcrypto } = require('crypto');

// ── Polyfill / setup ────────────────────────────────────────────────────
// Node 19+ already exposes `crypto` as the WebCrypto global, identical to
// the browser API. We keep a local `webcrypto` binding for clarity in
// helper code below, but the production modules consume `crypto.subtle`
// directly.
// Debug helpers used by all three modules. Silence them under test.
global.debugLog = () => {};
global.debugError = () => {};
global.debugWarn = () => {};
// Protocol version: defaults to 1 inside _decryptMessageImpl when unset.
// Set it explicitly to be loud about what we are testing.
global.PINCHAT_PROTOCOL_VERSION = 1;

// crypto.js must be required FIRST so it promotes AAD_FIELD_TYPES,
// encodeAADWithLengthPrefix and ChainRatchet onto globalThis before
// double-ratchet.js evaluates and references them.
const { ChainRatchet, AAD_FIELD_TYPES, encodeAADWithLengthPrefix } = require('../static/js/crypto.js');
const { IdentityKeyManager } = require('../static/js/identity.js');
const { DoubleRatchet } = require('../static/js/double-ratchet.js');

const ROOM = '00000000-0000-0000-0000-000000000001';
const ALICE_ID = '11111111-1111-1111-1111-111111111111';
const BOB_ID = '22222222-2222-2222-2222-222222222222';

// ── Helpers ──────────────────────────────────────────────────────────────

/**
 * Build a synchronised pair of Double Ratchets that share an identical
 * `sharedSecret`. Alice plays initiator, Bob plays responder. Peer identity
 * public keys are cross-imported so signed-header verification works on
 * both sides.
 */
async function setupPair() {
    const aliceIdent = new IdentityKeyManager();
    const bobIdent = new IdentityKeyManager();
    await aliceIdent.generateIdentityKeypair();
    await bobIdent.generateIdentityKeypair();

    const aliceIdPub = await aliceIdent.exportIdentityPublicKey();
    const bobIdPub = await bobIdent.exportIdentityPublicKey();
    await aliceIdent.importPeerIdentityPublicKey(bobIdPub);
    await bobIdent.importPeerIdentityPublicKey(aliceIdPub);

    // Simulated ECDH output. In production this comes from
    // ECDHKeyExchange.deriveSessionKey().
    const sharedSecret = new Uint8Array(32);
    webcrypto.getRandomValues(sharedSecret);

    // Initial ECDH keypairs for the Double Ratchet itself. We generate the
    // CryptoKeyPair objects here and pass them in via initialize(); the
    // production caller (app.js) does the same.
    const aliceKp = await webcrypto.subtle.generateKey(
        { name: 'ECDH', namedCurve: 'P-256' },
        false,
        ['deriveKey', 'deriveBits']
    );
    const bobKp = await webcrypto.subtle.generateKey(
        { name: 'ECDH', namedCurve: 'P-256' },
        false,
        ['deriveKey', 'deriveBits']
    );

    const alice = new DoubleRatchet(aliceIdent);
    const bob = new DoubleRatchet(bobIdent);
    await alice.initialize(sharedSecret, true, aliceKp, bobKp.publicKey);
    await bob.initialize(sharedSecret, false, bobKp, null);
    return { alice, bob };
}

function pass(label) {
    console.log(`  [OK] ${label}`);
}

// ── Test 1: C-01 baseline (sequential happy-path) ───────────────────────

async function testSequentialBaseline() {
    const { alice, bob } = await setupPair();
    for (let i = 0; i < 10; i++) {
        const enc = await alice.encryptMessage(`seq-${i}`, ROOM, ALICE_ID);
        assert.strictEqual(enc.header.n, i, `sequential counter at i=${i}`);
        const dec = await bob.decryptMessage(enc.payload, enc.header, ROOM, ALICE_ID);
        assert.strictEqual(dec.text, `seq-${i}`);
        assert.strictEqual(dec._outOfOrder, undefined, 'in-order msg must not be flagged');
    }
    pass('sequential 10 encrypt/decrypt round-trip');
}

// ── Test 2: C-01 concurrent encryption produces monotone counters ───────

async function testConcurrentEncryptMonotonicCounters() {
    const { alice } = await setupPair();
    const N = 50;
    // Fire all encrypts in a single microtask burst. With the mutex in place
    // each call observes the chain state ratcheted by the previous one;
    // without the mutex multiple calls would read CK_0 and produce
    // HMAC(CK_0, "MessageKey-1"), HMAC(CK_0, "MessageKey-2"), … which the
    // peer cannot derive.
    const encrypted = await Promise.all(
        Array.from({ length: N }, (_, i) =>
            alice.encryptMessage(`conc-${i}`, ROOM, ALICE_ID)
        )
    );
    const counters = encrypted.map(e => e.header.n);
    assert.deepStrictEqual(
        counters,
        Array.from({ length: N }, (_, i) => i),
        `expected [0..${N - 1}] strictly sequential counters, got ${counters.join(',')}`
    );
    pass(`${N} concurrent encrypts produce strictly sequential counters`);
}

// ── Test 3: C-01 all concurrent encrypts decrypt at the peer ────────────

async function testConcurrentEncryptAllDecryptable() {
    const { alice, bob } = await setupPair();
    const N = 30;
    const encrypted = await Promise.all(
        Array.from({ length: N }, (_, i) =>
            alice.encryptMessage(`pair-${i}`, ROOM, ALICE_ID)
        )
    );
    // Counters are 0..N-1 by C-01 guarantee; decrypt in that order.
    encrypted.sort((a, b) => a.header.n - b.header.n);
    for (const { payload, header } of encrypted) {
        const dec = await bob.decryptMessage(payload, header, ROOM, ALICE_ID);
        assert.strictEqual(dec.text, `pair-${header.n}`);
    }
    pass(`${N} concurrent encrypts all decrypt at peer (no AEAD failure)`);
}

// ── Test 4: C-02 late delivery across a DH ratchet ──────────────────────

async function testDelayedCrossDhRound() {
    const { alice, bob } = await setupPair();

    // Round 1: Alice sends 5 messages.
    const round1 = [];
    for (let i = 0; i < 5; i++) {
        round1.push(await alice.encryptMessage(`a${i}`, ROOM, ALICE_ID));
    }
    // Bob receives only a0 and a1 (Nr=2 afterwards).
    await bob.decryptMessage(round1[0].payload, round1[0].header, ROOM, ALICE_ID);
    await bob.decryptMessage(round1[1].payload, round1[1].header, ROOM, ALICE_ID);

    // Bob replies → triggers Bob's send-side DH ratchet (rc -> 1 on his side).
    const b0 = await bob.encryptMessage('bob reply', ROOM, BOB_ID);
    // Alice receives → her receive-side DH ratchet (rc -> 1 on her side).
    const decB0 = await alice.decryptMessage(b0.payload, b0.header, ROOM, BOB_ID);
    assert.strictEqual(decB0.text, 'bob reply');

    // Alice sends round 2 message. This uses the new sendingChain derived
    // during her receive-side DH ratchet. header.pn = 5 (her round-1 Ns).
    const round2_a0 = await alice.encryptMessage('a-round2-0', ROOM, ALICE_ID);
    assert.strictEqual(round2_a0.header.pn, 5, 'pn must report previous chain length');
    assert.strictEqual(round2_a0.header.rc, 1, 'ratchetCount must be 1 after one DH ratchet');

    // Bob receives round 2 message. This triggers:
    //   - skipMessageKeys(5)  → stores OLD_DH:2, OLD_DH:3, OLD_DH:4 in skippedKeys
    //   - performDHRatchetOnReceive(newAliceDh)
    //   - decrypt round2_a0 in the fresh receiving chain
    const decRound2 = await bob.decryptMessage(round2_a0.payload, round2_a0.header, ROOM, ALICE_ID);
    assert.strictEqual(decRound2.text, 'a-round2-0');
    assert.strictEqual(bob.skippedKeys.size, 3, 'three skipped keys must be stored after the skip');

    // Now the delayed round-1 messages a2, a3, a4 arrive. Without the C-02
    // short-circuit, each one would hit isNewKey=true (header.dh is the OLD
    // dh, but bob.DHrRaw is the NEW one), trigger a spurious DH ratchet, and
    // the AEAD would fail. With the fix, the short-circuit finds the key in
    // skippedKeys, decrypts, and flags _outOfOrder=true.
    for (const i of [2, 3, 4]) {
        const dec = await bob.decryptMessage(round1[i].payload, round1[i].header, ROOM, ALICE_ID);
        assert.strictEqual(dec.text, `a${i}`, `late a${i} must decrypt via skippedKeys`);
        assert.strictEqual(dec._outOfOrder, true, `late a${i} must be flagged _outOfOrder`);
    }
    assert.strictEqual(bob.skippedKeys.size, 0, 'all skipped keys consumed by late deliveries');

    pass('late messages from previous DH chain decrypt via skippedKeys (C-02)');
}

// ── Test 5: C-05 DH private keys are non-extractable ────────────────────

async function testDhPrivateNonExtractable() {
    const { alice, bob } = await setupPair();

    // Right after initialize().
    await assert.rejects(
        webcrypto.subtle.exportKey('pkcs8', alice.DHs.privateKey),
        /not extractable|InvalidAccess/i,
        'initialize: alice.DHs.privateKey must be non-extractable'
    );
    await assert.rejects(
        webcrypto.subtle.exportKey('pkcs8', bob.DHs.privateKey),
        /not extractable|InvalidAccess/i,
        'initialize: bob.DHs.privateKey must be non-extractable'
    );

    // Force a Bob send-side DH ratchet by having Alice send first, Bob
    // receive (sets hasRatchetedSinceReceive=false), then Bob encrypt
    // (triggers performSendSideDHRatchet).
    const a0 = await alice.encryptMessage('a0', ROOM, ALICE_ID);
    await bob.decryptMessage(a0.payload, a0.header, ROOM, ALICE_ID);
    const b0 = await bob.encryptMessage('b0', ROOM, BOB_ID);  // send-side ratchet
    assert.strictEqual(b0.header.rc, 1, 'Bob must have ratcheted exactly once');

    await assert.rejects(
        webcrypto.subtle.exportKey('pkcs8', bob.DHs.privateKey),
        /not extractable|InvalidAccess/i,
        'send-side ratchet: bob.DHs.privateKey must remain non-extractable'
    );

    // Force an Alice receive-side DH ratchet by having her decrypt b0
    // (whose dh is brand new).
    await alice.decryptMessage(b0.payload, b0.header, ROOM, BOB_ID);
    assert.strictEqual(alice.ratchetCount, 1, 'Alice must have receive-ratcheted once');

    await assert.rejects(
        webcrypto.subtle.exportKey('pkcs8', alice.DHs.privateKey),
        /not extractable|InvalidAccess/i,
        'receive-side ratchet: alice.DHs.privateKey must remain non-extractable'
    );

    // Imported peer DH public keys must also be non-extractable: if they
    // were exportable, an XSS could recover the raw bytes and check them
    // against precomputed group elements for traffic analysis. The raw
    // bytes ARE retained in DHrRaw — that is fine: it is a side-channel
    // we already chose to expose, see comments in skipMessageKeys.
    await assert.rejects(
        webcrypto.subtle.exportKey('raw', alice.DHr),
        /not extractable|InvalidAccess/i,
        'alice.DHr (peer public) must be non-extractable'
    );
    await assert.rejects(
        webcrypto.subtle.exportKey('raw', bob.DHr),
        /not extractable|InvalidAccess/i,
        'bob.DHr (peer public) must be non-extractable'
    );

    pass('DH private keys non-extractable across initialize, send- and receive-side ratchets');
    pass('Peer DH public keys (DHr) imported non-extractable');
}

// ── Test 6: F-10 encrypt-path rollback on AEAD failure ──────────────────
//
// _encryptMessageImpl mutates Ns, sendingChain (counter + chainKeyMaterial)
// and, on a send-side DH ratchet, DHs / rootKey / ratchetCount across multiple
// await points. F-10 added a _drSnapshot + try/catch + Object.assign rollback
// mirroring the decrypt path. We assert two invariants:
//
//   (a) when crypto.subtle.encrypt throws synthetically, encryptMessage
//       rejects AND the public ratchet counters (Ns, ratchetCount, header.n
//       that would have been emitted) remain unchanged;
//   (b) the very next legitimate encrypt produces the SAME counter the
//       failed one would have produced (i.e. the chain was not consumed).
//       Bob can still decrypt it.

async function testEncryptRollbackOnAeadFailure() {
    const { alice, bob } = await setupPair();

    // Warm up: send a few in-order messages so we are well past the initial
    // state and any first-message branching.
    for (let i = 0; i < 3; i++) {
        const enc = await alice.encryptMessage(`warm-${i}`, ROOM, ALICE_ID);
        await bob.decryptMessage(enc.payload, enc.header, ROOM, ALICE_ID);
    }

    // Capture state just before the synthetic-failure call.
    const snapshot = {
        Ns: alice.Ns,
        ratchetCount: alice.ratchetCount,
        sendingChainCounter: alice.sendingChain.messageNumber,
        // chainKeyMaterial is a Uint8Array — copy bytes for byte-comparison
        sendingChainKey: new Uint8Array(alice.sendingChain.chainKeyMaterial),
        DHsSignature: alice.DHsSignature,
    };

    // Monkey-patch crypto.subtle.encrypt to throw on the next call only.
    // The DoubleRatchet implementation reads `crypto.subtle.encrypt` directly,
    // and Node 19+ aliases globalThis.crypto to webcrypto — so patching the
    // bound encrypt on the global subtle reaches the production code.
    const realEncrypt = webcrypto.subtle.encrypt.bind(webcrypto.subtle);
    let nextEncryptThrows = true;
    webcrypto.subtle.encrypt = async function patched(...args) {
        if (nextEncryptThrows) {
            nextEncryptThrows = false;
            throw new Error('synthetic AES-GCM encrypt failure (F-10 regression)');
        }
        return realEncrypt(...args);
    };

    let threw = false;
    try {
        await alice.encryptMessage('would-fail', ROOM, ALICE_ID);
    } catch (e) {
        threw = true;
    }
    assert.strictEqual(threw, true, 'encryptMessage must propagate the synthetic encrypt failure');

    // Assert state has been rolled back.
    assert.strictEqual(alice.Ns, snapshot.Ns, 'Ns must be restored after rollback');
    assert.strictEqual(alice.ratchetCount, snapshot.ratchetCount, 'ratchetCount must be restored');
    assert.strictEqual(
        alice.sendingChain.messageNumber,
        snapshot.sendingChainCounter,
        'sendingChain.messageNumber must be restored'
    );
    assert.strictEqual(alice.DHsSignature, snapshot.DHsSignature, 'DHsSignature must be restored');

    // Byte-compare the chain key material. If the chain ratcheted forward
    // during the failed encrypt and we did NOT roll back, this would differ.
    assert.strictEqual(
        alice.sendingChain.chainKeyMaterial.length,
        snapshot.sendingChainKey.length,
        'sendingChain.chainKeyMaterial length must match snapshot'
    );
    for (let i = 0; i < snapshot.sendingChainKey.length; i++) {
        assert.strictEqual(
            alice.sendingChain.chainKeyMaterial[i],
            snapshot.sendingChainKey[i],
            `sendingChain.chainKeyMaterial[${i}] must match snapshot (rollback)`
        );
    }

    // Restore and assert forward progress: the next legitimate encrypt MUST
    // produce the counter the failed one would have produced (chain was not
    // consumed), and Bob MUST be able to decrypt.
    webcrypto.subtle.encrypt = realEncrypt;
    const recover = await alice.encryptMessage('after-rollback', ROOM, ALICE_ID);
    assert.strictEqual(
        recover.header.n,
        snapshot.Ns,
        'next encrypt after rollback must reuse the unconsumed counter'
    );
    const dec = await bob.decryptMessage(recover.payload, recover.header, ROOM, ALICE_ID);
    assert.strictEqual(dec.text, 'after-rollback');

    pass('encrypt path rolls back ratchet state on AEAD failure (F-10)');
}

async function testStateCompromiseDoesNotRecoverPastMessages() {
    const { alice } = await setupPair();
    const captured = await alice.encryptMessage('pfs-past', ROOM, ALICE_ID);
    for (let i = 0; i < 4; i++) {
        await alice.encryptMessage(`pfs-${i}`, ROOM, ALICE_ID);
    }

    // A compromised current root key must not be a parent of the initial
    // sending chain. Reconstructing CK0 here would break PFS.
    const attemptedInitialChain = await alice.hkdf(
        alice.rootKey, new Uint8Array(32), 'InitiatorToResponder', 32,
    );
    const chain = new ChainRatchet();
    await chain.initialize(attemptedInitialChain);
    const { key } = await chain.deriveMessageKey();
    const raw = alice.base64urlToArrayBuffer(captured.payload);
    const aad = encodeAADWithLengthPrefix([
        { type: AAD_FIELD_TYPES.ROOM_ID, value: ROOM },
        { type: AAD_FIELD_TYPES.SENDER_ID, value: ALICE_ID },
        { type: AAD_FIELD_TYPES.MESSAGE_NUMBER, value: 0 },
        { type: AAD_FIELD_TYPES.MESSAGE_TYPE, value: 'message' },
        { type: AAD_FIELD_TYPES.RATCHET_COUNT, value: 0 },
        { type: AAD_FIELD_TYPES.PREVIOUS_CHAIN_LENGTH, value: 0 },
    ]);

    let recovered = true;
    try {
        await webcrypto.subtle.decrypt(
            { name: 'AES-GCM', iv: raw.slice(0, 12), additionalData: aad },
            key,
            raw.slice(12),
        );
    } catch (_) {
        recovered = false;
    }
    assert.strictEqual(recovered, false, 'current root must not regenerate a past message key');
    pass('state compromise does not recover past chain messages (PFS)');
}

